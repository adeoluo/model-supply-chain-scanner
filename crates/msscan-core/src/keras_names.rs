pub fn is_builtin_class(name: &str) -> bool {
    CLASSES.binary_search(&name).is_ok()
}

/// Losses, metrics and activations are named in lower case, and metric names ignore case.
pub fn is_builtin_function(name: &str) -> bool {
    FUNCTIONS.binary_search(&name).is_ok()
        || FUNCTIONS.binary_search(&name.to_ascii_lowercase().as_str()).is_ok()
        || is_builtin_class(name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted_and_known_members() {
        assert!(CLASSES.windows(2).all(|w| w[0] < w[1]));
        assert!(FUNCTIONS.windows(2).all(|w| w[0] < w[1]));
        assert!(is_builtin_class("Dense") && is_builtin_class("CuDNNLSTM") && !is_builtin_class("MaliciousLayer"));
        assert!(is_builtin_function("mse") && is_builtin_function("relu") && is_builtin_function("AUC"));
        assert!(!is_builtin_function("malicious_loss"));
    }
}
