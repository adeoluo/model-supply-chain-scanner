//! Report renderers: text, JSON, SARIF 2.1.0 and the Markdown rule catalog.

use crate::finding::{Severity, RULES};
use crate::scan::Report;
use serde_json::{json, Value};
use std::fmt::Write;

/// Human-readable report; findings below `min` are hidden.
pub fn text(reports: &[Report], min: Severity) -> String {
    let mut out = String::new();
    for r in reports {
        let _ = writeln!(
            out,
            "{}  [{}]  {}  risk {}",
            r.path,
            r.format,
            r.verdict.as_str().to_uppercase(),
            r.risk_score
        );
        if let Some(e) = &r.error {
            let _ = writeln!(out, "  error: {e}");
        }
        for f in r.findings.iter().filter(|f| f.severity >= min) {
            let _ = writeln!(
                out,
                "  {:<8} {:<7} {}  ({})",
                f.severity.as_str(),
                f.rule,
                f.message,
                f.location
            );
        }
    }
    let flagged = reports
        .iter()
        .filter(|r| r.max_severity.is_some_and(|s| s >= Severity::High))
        .count();
    let _ = writeln!(
        out,
        "{} file(s) scanned, {flagged} with high or critical findings",
        reports.len()
    );
    out
}

fn sarif_level(s: Severity) -> &'static str {
    match s {
        Severity::Critical | Severity::High => "error",
        Severity::Medium => "warning",
        _ => "note",
    }
}

fn fingerprint(path: &str, rule: &str, location: &str, message: &str) -> String {
    // FNV-1a: stable across runs and platforms, enough to deduplicate alerts.
    let mut h: u64 = 0xcbf29ce484222325;
    for b in path
        .bytes()
        .chain([0])
        .chain(rule.bytes())
        .chain([0])
        .chain(location.bytes())
        .chain([0])
        .chain(message.bytes())
    {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

/// SARIF 2.1.0 log with one run, every rule in the catalog, and one result per finding at or
/// above `min`.
pub fn sarif(reports: &[Report], version: &str, min: Severity) -> Value {
    let rules: Vec<Value> = RULES
        .iter()
        .map(|r| {
            json!({
                "id": r.id,
                "name": r.name,
                "shortDescription": {"text": r.summary},
                "help": {"text": r.remediation},
                "defaultConfiguration": {"level": sarif_level(r.severity)},
                "properties": {
                    "security-severity": r.severity.sarif_score(),
                    "tags": ["security", r.cwe],
                    "precision": "high",
                }
            })
        })
        .collect();
    let mut results = Vec::new();
    for r in reports {
        for f in r.findings.iter().filter(|f| f.severity >= min) {
            let idx = RULES.iter().position(|x| x.id == f.rule).unwrap_or(0);
            results.push(json!({
                "ruleId": f.rule,
                "ruleIndex": idx,
                "level": sarif_level(f.severity),
                "message": {"text": format!("{} ({})", f.message, f.location)},
                "locations": [{
                    "physicalLocation": {"artifactLocation": {"uri": r.path.trim_start_matches("./")}},
                    "logicalLocations": [{"fullyQualifiedName": f.location, "kind": "member"}],
                }],
                "partialFingerprints": {"msscan/v1": fingerprint(&r.path, &f.rule, &f.location, &f.message)},
                "properties": {"severity": f.severity.as_str(), "security-severity": f.severity.sarif_score()},
            }));
        }
    }
    json!({
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {
                "name": "msscan",
                "version": version,
                "informationUri": "https://github.com/adeoluo/model-supply-chain-scanner",
                "rules": rules,
            }},
            "results": results,
        }]
    })
}

/// The rule catalog as Markdown (docs/RULES.md).
pub fn rules_markdown() -> String {
    let mut out = String::from(
        "# Rules\n\nGenerated by `msscan rules --format markdown`. Severity is the default; some \
         rules raise it when the evidence is stronger (for example a dynamic import that is also called).\n\n\
         | ID | Name | Severity | CWE | What it means | What to do |\n|---|---|---|---|---|---|\n",
    );
    for r in RULES {
        let _ = writeln!(
            out,
            "| {} | `{}` | {} | {} | {} | {} |",
            r.id,
            r.name,
            r.severity.as_str(),
            r.cwe,
            r.summary.replace('|', "\\|"),
            r.remediation.replace('|', "\\|")
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scan::{scan_bytes, Options};

    #[test]
    fn sarif_has_rules_and_results() {
        let r = scan_bytes(b"\x80\x02cos\ngetcwd\n)R.", "./m.pkl", &Options::default());
        let s = sarif(std::slice::from_ref(&r), "0.1.0", Severity::Low);
        assert_eq!(s["version"], "2.1.0");
        let run = &s["runs"][0];
        assert_eq!(run["tool"]["driver"]["rules"].as_array().unwrap().len(), RULES.len());
        let res = run["results"].as_array().unwrap();
        assert_eq!(res[0]["ruleId"], "MS101");
        assert_eq!(res[0]["level"], "error");
        assert_eq!(
            res[0]["locations"][0]["physicalLocation"]["artifactLocation"]["uri"],
            "m.pkl"
        );
        let rid = res[0]["ruleIndex"].as_u64().unwrap() as usize;
        assert_eq!(run["tool"]["driver"]["rules"][rid]["id"], "MS101");
        let again = sarif(&[r], "0.1.0", Severity::Low);
        assert_eq!(
            again["runs"][0]["results"][0]["partialFingerprints"],
            res[0]["partialFingerprints"]
        );
        assert_eq!(sarif_level(Severity::Medium), "warning");
        assert_eq!(sarif_level(Severity::Info), "note");
    }

    #[test]
    fn text_and_markdown() {
        let r = scan_bytes(b"\x80\x02cos\ngetcwd\n)R.", "m.pkl", &Options::default());
        let t = text(&[r], Severity::Low);
        assert!(t.contains("MALICIOUS") && t.contains("MS101") && t.contains("1 with high"));
        let md = rules_markdown();
        assert_eq!(md.lines().filter(|l| l.starts_with("| MS")).count(), RULES.len());
    }
}
